class Participant {
  final String id;
  final String email;
  final String name;
  final String avatar;
  final String uid;
  final String uidType;
  final String state;

  Participant({
    required this.id,
    required this.email,
    required this.name,
    required this.avatar,
    required this.uid,
    required this.uidType,
    required this.state,
  });
}